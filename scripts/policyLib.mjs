// Shared by scripts/bundle-policies.mjs and tests/unit/policies.test.ts.
// [ATTORNEY] The .md files are Counsel drafts. The "Drafting notes ... (delete this block before publishing)"
// blockquote is for the engineer/attorney and must never ship, so it is removed here before hashing.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const POLICY_DIR = join(ROOT, 'src', 'legal', 'policies');
export const GENERATED = join(POLICY_DIR, 'policies.generated.ts');

export const POLICIES = [
  { id: 'privacy', file: 'privacy-policy.md', exportName: 'PRIVACY_POLICY_DOC' },
  { id: 'health', file: 'consumer-health-data-privacy-policy.md', exportName: 'HEALTH_POLICY_DOC' },
];

export function stripDraftingNotes(md) {
  const lines = md.replace(/\r\n/g, '\n').split('\n');
  const start = lines.findIndex((l) => /^>\s*#{1,6}\s*Drafting notes/i.test(l));
  if (start === -1) return lines.join('\n');
  let end = start;
  while (end < lines.length && lines[end].startsWith('>')) end++;
  const out = [...lines.slice(0, start), ...lines.slice(end)];
  // Collapse the now-adjacent horizontal rules / blank lines left behind.
  const cleaned = [];
  for (const l of out) {
    const prev = cleaned.filter((x) => x.trim() !== '').at(-1);
    if (l.trim() === '---' && prev === '---') continue;
    if (l.trim() === '' && cleaned.length && cleaned.at(-1).trim() === '') continue;
    cleaned.push(l);
  }
  return cleaned.join('\n');
}

export function parsePolicy(md) {
  const title = /^#\s+(.+)$/m.exec(md)?.[1].trim();
  const version = /\*\*Version:\*\*\s*\[([^\]]+)\]/.exec(md)?.[1].trim();
  if (!title || !version) throw new Error('policy: missing title or **Version:** [..] line');
  const body = stripDraftingNotes(md);
  const sha256 = createHash('sha256').update(body, 'utf8').digest('hex');
  return { title, version, body, sha256 };
}

export function loadAll() {
  return POLICIES.map((p) => ({ ...p, ...parsePolicy(readFileSync(join(POLICY_DIR, p.file), 'utf8')) }));
}

export function renderGenerated(all = loadAll()) {
  const blocks = all.map(
    (p) =>
      `export const ${p.exportName} = {\n  id: ${JSON.stringify(p.id)},\n  version: ${JSON.stringify(p.version)},\n  title: ${JSON.stringify(p.title)},\n  sha256: ${JSON.stringify(p.sha256)},\n  body: ${JSON.stringify(p.body)},\n} as const;\n`,
  );
  return `// GENERATED by scripts/bundle-policies.mjs from the .md files next to this file. Do not edit; run \`npm run policies\`.\n// [ATTORNEY] Draft policy text. The drafting-notes block is stripped; sha256 is of exactly \`body\`.\n\n${blocks.join('\n')}`;
}
