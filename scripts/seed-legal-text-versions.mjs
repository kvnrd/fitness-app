// Generates supabase/migrations/20261117000600_phase4_legal_text_versions_seed.sql
// from the bundled policy bodies and in-app legal strings. Run after `npm run policies`
// or whenever a hashed legal string changes: `node scripts/seed-legal-text-versions.mjs`.
// The sha256 stored here is of exactly `full_text` (UTF-8), matching legalTextHash / policy hashes.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HEALTH_POLICY_DOC, PRIVACY_POLICY_DOC, TERMS_DOC } from '../src/legal/policies/policies.generated.ts';
import { HEALTH_POLICY, HEALTH_TEXT, PRIVACY_POLICY, TERMS, VERSIONS, legalTexts } from '../src/legal/text.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'supabase', 'migrations', '20261117000600_phase4_legal_text_versions_seed.sql');

const sha256 = (s) => createHash('sha256').update(s, 'utf8').digest('hex');

/** Bundled texts whose hashes are (or may be) logged on consent rows. Personalized parent variants
 *  are archived at write time once the write path passes the exact shown text; the defaults here
 *  use the in-app "your teen" placeholders. */
const rows = [
  { kind: 'terms', version: TERMS.version, sha256: TERMS.hash, text: TERMS_DOC.body },
  { kind: 'privacy_policy', version: PRIVACY_POLICY.version, sha256: PRIVACY_POLICY.hash, text: PRIVACY_POLICY_DOC.body },
  { kind: 'health_policy', version: HEALTH_POLICY.version, sha256: HEALTH_POLICY.hash, text: HEALTH_POLICY_DOC.body },
  { kind: 'health_collection', version: VERSIONS.health, text: HEALTH_TEXT },
  { kind: 'health_with_ai', version: legalTexts.health().version, text: legalTexts.health().text },
  { kind: 'ai_adult', version: legalTexts.aiAdult().version, text: legalTexts.aiAdult().text },
  { kind: 'ai_teen', version: legalTexts.aiTeen().version, text: legalTexts.aiTeen().text },
  { kind: 'ai_parent', version: legalTexts.parentAi().version, text: legalTexts.parentAi().text },
  { kind: 'risk_adult', version: legalTexts.riskAdult().version, text: legalTexts.riskAdult().text },
  { kind: 'risk_parent', version: legalTexts.riskParent().version, text: legalTexts.riskParent().text },
  { kind: 'parent_attest', version: legalTexts.parentAttest().version, text: legalTexts.parentAttest().text },
  { kind: 'parent_health', version: legalTexts.parentHealth().version, text: legalTexts.parentHealth().text },
  { kind: 'parent_coach', version: legalTexts.parentCoach().version, text: legalTexts.parentCoach().text },
  { kind: 'coach_attest_general', version: legalTexts.coachAttestGeneral().version, text: legalTexts.coachAttestGeneral().text },
  { kind: 'coach_attest_minors', version: legalTexts.coachAttestMinors().version, text: legalTexts.coachAttestMinors().text },
].map((r) => {
  const digest = r.sha256 ?? sha256(r.text);
  if (r.sha256 && r.sha256 !== sha256(r.text)) {
    throw new Error(`hash mismatch for ${r.kind}: bundled sha256 does not match body`);
  }
  return { kind: r.kind, version: r.version, sha256: digest, text: r.text };
});

function dollarQuote(s) {
  let tag = 'legal';
  let n = 0;
  while (s.includes(`$${tag}$`)) tag = `legal${++n}`;
  return `$${tag}$${s}$${tag}$`;
}

const header = `-- Generated by scripts/seed-legal-text-versions.mjs from bundled policy bodies and in-app
-- legal strings. Do not edit by hand; re-run the script when a hashed text changes.
-- Each call is a no-op if the same kind+version+hash+text is already present, and raises if
-- a kind+version is reused with a different hash or body (append-only).
-- Counsel Rev 6: hashes are of the exact characters shown, including curly apostrophes (U+2019).
-- After a version is live, any text change (including typography) must bump the version.

`;

const body = rows
  .map(
    (r) =>
      `select private.put_legal_text_version(\n` +
      `  ${dollarQuote(r.kind)},\n` +
      `  ${dollarQuote(r.version)},\n` +
      `  ${dollarQuote(r.sha256)},\n` +
      `  ${dollarQuote(r.text)}\n` +
      `);\n`,
  )
  .join('\n');

writeFileSync(OUT, header + body);
console.log(`wrote ${OUT} (${rows.length} texts)`);
